#!/usr/bin/env python3
"""Generate Viola dataset analysis figures and markdown report.

Examples:
  python -m analysis.viz.generate_all
  python -m analysis.viz.generate_all --raw datasets/raw --figures-dir analysis/figures
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from analysis.viz.data import (  # noqa: E402
    inventory_dd,
    quickdraw_counts,
    sketchyscene_counts,
    tu_berlin_categories,
)
from analysis.viz.fig_class_balance import (  # noqa: E402
    plot_dataset_overview,
    plot_dd_class_balance,
    plot_dd_size_intensity,
)
from analysis.viz.fig_montages import (  # noqa: E402
    plot_dd_montage,
    plot_quickdraw_montage,
    plot_sketchyscene_montage,
    plot_tu_berlin_montage,
)

TU_CATS = ("house", "tree", "face", "person sitting", "person walking", "palm tree")


def write_report(
    path: Path,
    *,
    dd,
    qd,
    ss,
    tu,
    generated: list,
) -> Path:
    ratio = (dd.de / dd.nor) if dd.nor else 0.0
    imbalance = dd.nor > 0 and ratio < 0.15
    lines = [
        "# Viola dataset report",
        "",
        "Auto-generated by `python -m analysis.viz.generate_all`.",
        "",
        "## Summary",
        "",
        f"| Dataset | Count / notes |",
        f"|---------|---------------|",
        f"| **DD** | total={dd.total}, Nor={dd.nor}, De={dd.de}, unknown={dd.unknown} |",
        f"| QuickDraw | " + ", ".join(f"{k}={v:,}" for k, v in qd.items()) + " |",
        f"| SketchyScene-7k | " + ", ".join(f"{k}={v:,}" for k, v in ss.items())
        + f" (sum={sum(ss.values()):,}) |",
        f"| TU-Berlin (HTP cats) | " + ", ".join(f"{k}={v}" for k, v in tu.items())
        + f" (sum={sum(tu.values())}) |",
        "",
        "## DD findings",
        "",
        f"- Filename-parsed labels: **{dd.nor} Nor** / **{dd.de} De** (ratio De/Nor = **{ratio:.4f}**).",
    ]
    if imbalance:
        lines += [
            "- **⚠ Severe class imbalance.** Do not train with unweighted CE alone;",
            "  prefer class weights, oversampling minority `De`, or focal loss.",
            "  Folder ids (`0/`, `1/`) are **unreliable** — always parse `Nor`/`De` from filenames.",
        ]
    if dd.by_folder:
        lines.append("- Per-folder counts:")
        for folder, ctr in sorted(dd.by_folder.items()):
            lines.append(
                f"  - `{folder}/`: Nor={ctr.get('Nor', 0)}, De={ctr.get('De', 0)}, "
                f"unknown={ctr.get('unknown', 0)}"
            )
    if dd.severity:
        sev = ", ".join(f"{k}={v}" for k, v in sorted(dd.severity.items()))
        lines.append(f"- Severity tags (from filename suffix): {sev}")
    if dd.widths:
        import numpy as np

        lines.append(
            f"- Image size (subsample n={len(dd.widths)}): "
            f"W∈[{min(dd.widths)}, {max(dd.widths)}], "
            f"H∈[{min(dd.heights)}, {max(dd.heights)}], "
            f"mean intensity≈{float(np.mean(dd.mean_intensities)):.1f}"
        )
    lines += [
        "",
        "## Role of public sketch sets",
        "",
        "- **QuickDraw** / **TU-Berlin**: sketch-domain bootstrap only — **not** clinical depression labels.",
        "- **SketchyScene**: multi-object scene composition priors; no Nor/De labels.",
        "",
        "## Generated figures",
        "",
    ]
    for g in generated:
        lines.append(f"- `{Path(g).name}`")
    lines.append("")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def main() -> int:
    parser = argparse.ArgumentParser(description="Viola dataset visualization / analysis")
    parser.add_argument("--raw", type=Path, default=ROOT / "datasets" / "raw")
    parser.add_argument("--figures-dir", type=Path, default=ROOT / "analysis" / "figures")
    parser.add_argument("--report", type=Path, default=ROOT / "analysis" / "dataset_report.md")
    parser.add_argument("--include-augmented", action="store_true")
    args = parser.parse_args()

    raw = args.raw.resolve()
    figures_dir = args.figures_dir.resolve()
    figures_dir.mkdir(parents=True, exist_ok=True)

    generated: list[str] = []

    dd_root = raw / "htp_depression_dd"
    dd = inventory_dd(dd_root, include_augmented=args.include_augmented)
    print(f"DD: total={dd.total} Nor={dd.nor} De={dd.de}")

    qd_root = raw / "quickdraw" / "numpy_bitmap"
    qd = quickdraw_counts(qd_root) if qd_root.is_dir() else {}
    print(f"QuickDraw: {qd}")

    ss_root = raw / "sketchyscene" / "SketchyScene-7k"
    ss = sketchyscene_counts(ss_root) if ss_root.is_dir() else {}
    print(f"SketchyScene: {ss}")

    tu_root = raw / "tu_berlin" / "svg"
    tu = tu_berlin_categories(tu_root, TU_CATS) if tu_root.is_dir() else {}
    print(f"TU-Berlin: {tu}")

    if dd.total:
        p = plot_dd_class_balance(dd, figures_dir / "fig_dd_class_balance.png")
        generated.append(str(p))
        p = plot_dd_montage(figures_dir / "fig_dd_montage.png", dd.nor_paths, dd.de_paths)
        if p:
            generated.append(str(p))
        p = plot_dd_size_intensity(dd, figures_dir / "fig_dd_size_intensity.png")
        if p:
            generated.append(str(p))

    p = plot_dataset_overview(
        figures_dir / "fig_dataset_overview.png",
        dd=dd, quickdraw=qd, sketchyscene=ss, tu_berlin=tu,
    )
    generated.append(str(p))

    if qd_root.is_dir():
        p = plot_quickdraw_montage(figures_dir / "fig_quickdraw_montage.png", qd_root)
        if p:
            generated.append(str(p))

    if ss_root.is_dir():
        p = plot_sketchyscene_montage(figures_dir / "fig_sketchyscene_montage.png", ss_root)
        if p:
            generated.append(str(p))

    if tu_root.is_dir():
        p = plot_tu_berlin_montage(figures_dir / "fig_tu_berlin_montage.png", tu_root)
        if p:
            generated.append(str(p))

    report = write_report(args.report.resolve(), dd=dd, qd=qd, ss=ss, tu=tu, generated=generated)
    generated.append(str(report))

    manifest = {
        "raw": str(raw),
        "figures_dir": str(figures_dir),
        "dd": {"total": dd.total, "nor": dd.nor, "de": dd.de, "unknown": dd.unknown},
        "quickdraw": qd,
        "sketchyscene": ss,
        "tu_berlin": tu,
        "generated": generated,
    }
    (figures_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps(manifest, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
